defmodule Valimc.Commands.Parser.Tree do
  @moduledoc """
  Vanilla's command tree pruned to what ValiMC executes (VMC-053, VMC-077o).

  `priv/commands/tree.json` is generated by `CommandTreeOracle tree` from the
  pinned dedicated server: dispatcher order, permission levels, executable flags,
  redirects, argument parsers with their network properties and suggestion IDs.
  `Valimc.Commands.registry/0` names the commands ValiMC runs; this module keeps
  their executable nodes (but excepted paths), their ancestors, redirects to
  kept nodes and aliases, and encodes one commands packet per permission level
  (vanilla's `Commands.sendCommands` with `fillUsableCommands`).
  """
  alias Valimc.Protocol.Wire

  defmodule Node do
    @moduledoc """
    A tree node. `command` is the top-level command name an executable node
    runs (`Valimc.Commands.registry/0`); `modifier` is the slot a forking
    node (`execute`'s redirects) will fill.
    """
    defstruct [
      :name,
      :type,
      :level,
      :restricted,
      :parser,
      :parser_id,
      :properties,
      :bytes,
      :suggestions,
      :redirect,
      :command,
      :modifier,
      path: [],
      children: []
    ]
  end

  # Read at runtime: as a compiled literal the tree made a 108 MB module (a038f96).
  defp facts, do: Valimc.Data.Facts.read!("commands/tree.json")

  @doc "The full vanilla tree as nested JSON maps (for coverage reports)."
  def vanilla, do: facts()["children"]

  @doc """
  The tree for `commands`: name => options (`except:` paths, `only:` paths,
  `own: true` for a ValiMC command without a vanilla node, with an optional
  `tree:` callback for its subtree). Executable nodes
  run their command's name; redirects are kept when their target is.
  """
  def build(commands) do
    vanilla = facts()["children"]

    children =
      vanilla
      |> Enum.filter(&Map.has_key?(commands, &1["name"]))
      |> Enum.map(&prune(&1, [], commands[&1["name"]], &1["name"]))
      |> Enum.reject(&is_nil/1)

    kept = MapSet.new(paths(children))
    children = Enum.map(children, &drop_dangling(&1, kept))

    # Aliases (`tp`, `xp`, `tell`, `w`) are top-level redirects to kept commands.
    aliases =
      for json <- vanilla,
          json["redirect"] && MapSet.member?(kept, json["redirect"]) && !json["children"],
          do: node(json, [json["name"]], nil, [])

    by_name = Map.new(children ++ aliases, &{&1.name, &1})
    ordered = for json <- vanilla, node = by_name[json["name"]], do: node

    own =
      for {name, options} <- commands,
          options[:own],
          do:
            if(options[:tree],
              do: options[:tree].(),
              else: %Node{
                name: name,
                type: :literal,
                level: 0,
                restricted: false,
                command: name,
                path: [name]
              }
            )

    %Node{
      name: "",
      type: :root,
      level: 0,
      restricted: false,
      children: ordered ++ Enum.sort_by(own, &(&1.name != "stats"))
    }
  end

  defp prune(json, parent, options, name) do
    path = parent ++ [json["name"]]
    children = Enum.flat_map(json["children"] || [], &List.wrap(prune(&1, path, options, name)))
    command = if json["executable"] && runs?(options, path), do: name

    cond do
      # A redirect stays when its target does (`drop_dangling/2`).
      json["redirect"] -> node(json, path, command, [])
      command != nil or children != [] -> node(json, path, command, children)
      true -> nil
    end
  end

  defp runs?(options, path) do
    case Keyword.fetch(options, :only) do
      {:ok, only} -> path in only
      :error -> path not in Keyword.get(options, :except, [])
    end
  end

  defp drop_dangling(node, kept) do
    children =
      for child <- node.children,
          child.redirect == nil or MapSet.member?(kept, child.redirect),
          do: drop_dangling(child, kept)

    %{node | children: children}
  end

  defp node(json, path, command, children) do
    %Node{
      name: json["name"],
      type: String.to_atom(json["type"]),
      level: json["level"],
      restricted: json["restricted"],
      parser: json["parser"],
      parser_id: json["parser_id"],
      properties: json["properties"] || %{},
      bytes: if(json["bytes"], do: Base.decode16!(json["bytes"], case: :lower)),
      suggestions: json["suggestions"],
      redirect: json["redirect"],
      command: command,
      path: path,
      children: children
    }
  end

  defp paths(nodes), do: Enum.flat_map(nodes, &[&1.path | paths(&1.children)])

  @doc "Every node of the tree by path."
  def by_path(root), do: Map.new(walk(root), &{&1.path, &1})

  @doc """
  The node at `path` below `root`. Each node holds its children once: copying a
  tree (a literal, `:persistent_term`) does not keep shared subterms, so a second
  view of them per node grows with every level.
  """
  def node!(root, path) do
    Enum.reduce(path, root, fn name, node ->
      Enum.find(node.children, &(&1.name == name)) ||
        raise KeyError, key: path
    end)
  end

  defp walk(node), do: [node | Enum.flat_map(node.children, &walk/1)]

  @doc "The commands packet payload for a source of permission `level`."
  def graph(root, level) do
    nodes = by_path(root)
    usable = fn node -> node.level <= level end
    order = enumerate([root], usable, nodes, %{}, [])
    ids = Map.new(Enum.with_index(order), fn {node, i} -> {node.path, i} end)

    IO.iodata_to_binary([
      Wire.varint(length(order)),
      Enum.map(order, &entry(&1, ids, usable, nodes)),
      Wire.varint(ids[[]])
    ])
  end

  # Vanilla's breadth-first `enumerateNodes`: children, then the redirect target.
  defp enumerate([], _usable, _nodes, _seen, acc), do: Enum.reverse(acc)

  defp enumerate([node | queue], usable, nodes, seen, acc) do
    if Map.has_key?(seen, node.path) do
      enumerate(queue, usable, nodes, seen, acc)
    else
      next = Enum.filter(node.children, usable)
      next = if node.redirect, do: next ++ [Map.fetch!(nodes, node.redirect)], else: next
      enumerate(queue ++ next, usable, nodes, Map.put(seen, node.path, true), [node | acc])
    end
  end

  defp entry(node, ids, usable, nodes) do
    type = %{root: 0, literal: 1, argument: 2}[node.type]
    children = for child <- node.children, usable.(child), do: ids[child.path]

    flags =
      type
      |> flag(node.command != nil, 4)
      |> flag(node.redirect != nil, 8)
      |> flag(node.suggestions != nil, 16)
      |> flag(node.restricted, 32)

    [
      flags,
      Wire.varint(length(children)),
      Enum.map(children, &Wire.varint/1),
      if(node.redirect, do: Wire.varint(ids[Map.fetch!(nodes, node.redirect).path]), else: []),
      case node.type do
        :root ->
          []

        :literal ->
          Wire.string(node.name)

        :argument ->
          [
            Wire.string(node.name),
            Wire.varint(node.parser_id),
            node.bytes,
            if(node.suggestions, do: Wire.string(node.suggestions), else: [])
          ]
      end
    ]
  end

  defp flag(flags, true, bit), do: Bitwise.bor(flags, bit)
  defp flag(flags, _, _), do: flags
end
